class forloop{
    public static void main(String [] args){
    for(int i=0; i<=5; i++){
        System.out.println("The value of i is: " + i);
    }
    
    for(int i=0; i<=5; i=i+1){
        System.out.println("The value of i is: " + i);
    }
    for(int i=1;i<=10;i=i+1){
        System.out.println("John");
    }
    }
}
